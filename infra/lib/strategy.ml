(* Generates the jail/service/deploy sh for the closed set of known app
   shapes, from each app's strategy_config. The shared boilerplate here
   (FreeBSD base fetch, jail.conf entry, service user) is what every app's
   hand-written jail script used to duplicate. extra_steps is the escape hatch for logic that doesn't fit
   any strategy's shape: each step is a script beside the generated one,
   run after the service user is created (so a step can chown to it, as a
   backup job's install does) and before any service is enabled.
   Every app's generated script has built a real jail through infra
   jail-test; the goldens in test/golden/example and test/golden/strategy
   pin the render. *)

(* Renders already-parsed strategies: App_config stores the Strategy_config.t
   parsed at load, so nothing here parses or rejects declarations. *)

(* Shared across every FreeBSD-jail strategy: fetch the release base once,
   pin resolv.conf and copy the host's localtime, create the jail's
   dedicated dirs (plus [extra_dirs], paths inside the jail root), turn off
   syslogd and sendmail -- the same idioms as the hand-written scripts it
   replaced. Split from render_jail_start, which writes the jail.conf entry
   and jail_list, so a strategy can run host-side steps (the ZFS mount
   check) after setup but before the jail is registered and starts. The
   jail.conf guard matches the block's opening line, so <app>'s guard is
   not satisfied by an <app>test block.

   [jail] names the host-side resources: the jail.conf block, /jails/<jail>,
   jail_list and every jexec/service jail target. [app] names everything
   inside the jail: the service user, /opt, /var/db, /etc, /var/log and
   /var/run dirs, the rc.d script and service. The two are equal except
   under infra jail-test, which renders the real app into a throwaway
   jail.

   [layout]: [Code_dir], the original one, makes /opt/<app> a directory and
   the service user's HOME. [Release_pointer], the native kinds' layout,
   leaves /opt/<app> to artifact activation, which makes it a pointer into
   /opt/.infra-releases; HOME is /var/db/<app>. A jail still on the old
   layout is refused before anything is touched (jails were moved off it
   in 2026-10 by a one-off infra up --adopt, since removed). *)
type layout = Code_dir | Release_pointer

let render_jail_setup ?(extra_dirs = []) ?(layout = Code_dir) ?(stop_before_setup = true) ~jail ~app ~jail_ip () =
  String.concat "\n"
    ([
      "#!/bin/sh";
      Printf.sprintf "# Generated by Strategy for %s -- do not hand-edit" jail;
      "set -eu";
      {|SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"|};
      Printf.sprintf "JAIL=%s" jail;
      Printf.sprintf "APP=%s" app;
      Printf.sprintf "JAIL_IP=%s" jail_ip;
      {|JROOT="/jails/${JAIL}"|};
      {|FREEBSD_VERSION="$(freebsd-version -u | cut -d- -f1-2)"|};
      {|log() { echo "==> [${JAIL}] $*"; }|};
    ]
    @ (match layout with
      | Code_dir -> []
      | Release_pointer ->
          [
            {|if [ -d "${JROOT}/opt/${APP}" ] && [ ! -L "${JROOT}/opt/${APP}" ]; then|};
            {|  echo "${JAIL}: /opt/${APP} is a directory, the old pre-release layout; refusing to bootstrap over it" >&2|};
            "  exit 1";
            "fi";
          ])
    @ (if stop_before_setup then [ {|service jail stop "$JAIL" 2>/dev/null || true|} ] else [])
    @ [
      {|if [ ! -f "${JROOT}/bin/sh" ]; then|};
      {|  mkdir -p "$JROOT"|};
      {|  fetch -o /tmp/base.txz \|};
      {|    "https://download.freebsd.org/releases/amd64/${FREEBSD_VERSION}/base.txz"|};
      {|  tar -xpf /tmp/base.txz -C "$JROOT"|};
      {|  rm /tmp/base.txz|};
      "fi";
      {|chflags noschg "${JROOT}/etc/resolv.conf" 2>/dev/null || true|};
      {|echo "nameserver 1.1.1.1" >"${JROOT}/etc/resolv.conf"|};
      {|chflags schg "${JROOT}/etc/resolv.conf"|};
      {|cp /etc/localtime "${JROOT}/etc/localtime"|};
      (match layout with
       | Code_dir -> {|mkdir -p "${JROOT}/opt/${APP}" "${JROOT}/var/db/${APP}" \|}
       | Release_pointer -> {|mkdir -p "${JROOT}/opt/.infra-releases" "${JROOT}/var/db/${APP}" \|});
      {|  "${JROOT}/etc/${APP}" "${JROOT}/var/log/${APP}" "${JROOT}/var/run/${APP}"|};
    ]
    @ (match extra_dirs with
      | [] -> []
      | dirs ->
          [
            "mkdir -p "
            ^ String.concat " " (List.map (Printf.sprintf {|"${JROOT}%s"|}) dirs);
          ])
    @ [
      {|grep -q "syslogd_enable" "${JROOT}/etc/rc.conf" 2>/dev/null || cat >>"${JROOT}/etc/rc.conf" <<'EOF'|};
      {|syslogd_enable="NO"|};
      {|sendmail_enable="NONE"|};
      "EOF";
    ])

(* Registers the jail -- its jail.conf block, idempotently, and its
   jail_list entry -- then starts it. Registration is kept with the start,
   as in the hand-written scripts this replaced, so a strategy that verifies host state
   between setup and start (a ZFS mount) leaves nothing registered to
   autostart when that verification fails. *)
let render_jail_start =
  String.concat "\n"
    [
      {|grep -q "^${JAIL}[[:space:]]*{" /etc/jail.conf 2>/dev/null || cat >>/etc/jail.conf <<EOF|};
      "";
      "${JAIL} {";
      "    path          = /jails/${JAIL};";
      "    host.hostname = ${JAIL}.local;";
      "    ip4.addr      = lo1|${JAIL_IP}/32;";
      {|    exec.start    = "/bin/sh /etc/rc";|};
      {|    exec.stop     = "/bin/sh /etc/rc.shutdown";|};
      "    exec.clean;";
      "    mount.devfs;";
      "    allow.raw_sockets = 0;";
      "    allow.sysvipc    = 0;";
      "}";
      "EOF";
      {|sysrc -n jail_list | grep -qw "$JAIL" || sysrc jail_list+=" ${JAIL}"|};
      {|sysrc jail_enable="YES"|};
      {|service jail start "$JAIL" 2>/dev/null || service jail restart "$JAIL"|};
    ]

let render_jail_base ?extra_dirs ?layout ~jail ~app ~jail_ip () =
  String.concat "\n" [ render_jail_setup ?extra_dirs ?layout ~jail ~app ~jail_ip (); render_jail_start ]

(* Each step runs as its own sh from the script's directory; set -e aborts
   the script if a step fails. The jail's facts go on each step's command
   line rather than being exported: an exported JAIL would reach every later
   jexec in this script, and service(8) in the jail reads it as its -j
   option and re-execs into that jail from inside it ('jail not found').
   Every step is a plain file name beside the script -- App_config refuses
   any other at load (Strategy_config.parse_extra_steps) -- so it is spliced
   inside double quotes without expansion. *)
let render_extra_steps steps =
  List.map
    (fun step ->
      Printf.sprintf
        {|JAIL="$JAIL" JAIL_IP="$JAIL_IP" JROOT="$JROOT" APP="$APP" sh "${SCRIPT_DIR}/%s"|} step)
    steps

let render_service_user ?home ?(layout = Code_dir) ~jail ~app () =
  let home = Option.value home
      ~default:(match layout with Code_dir -> "/opt/" ^ app | Release_pointer -> "/var/db/" ^ app) in
  let owned = match layout with
    | Code_dir -> [ "/opt/"; "/var/db/"; "/var/log/"; "/var/run/" ]
    | Release_pointer -> [ "/var/db/"; "/var/log/"; "/var/run/" ] in
  String.concat "\n"
    [
      Printf.sprintf
        {|jexec "%s" pw useradd -n "%s" -d "%s" -s /usr/sbin/nologin \|}
        jail app home;
      Printf.sprintf {|  -c "%s service user" 2>/dev/null || true|} app;
      Printf.sprintf {|jexec "%s" chown -R "%s:%s" %s|} jail app app
        (String.concat " " (List.map (fun dir -> Printf.sprintf {|"%s%s"|} dir app) owned));
    ]

(* The native kinds' service: the generated rc script, enabled but not
   started, since nothing runs until the first activation installs a release.
   The operator writes /etc/<app>/env from the app's env.template; it is never
   written here, only given the ownership and mode the service can read. *)
let render_native_service (rc : Rc_script.t) =
  [
    {|mkdir -p "${JROOT}/usr/local/etc/rc.d"|};
    Printf.sprintf {|cat >"${JROOT}/usr/local/etc/rc.d/%s" <<'INFRA_RC'|} rc.service;
    String.trim rc.script;
    "INFRA_RC";
    Printf.sprintf {|chmod 0755 "${JROOT}/usr/local/etc/rc.d/%s"|} rc.service;
    Printf.sprintf {|jexec "$JAIL" sysrc %s_enable="YES"|} rc.service;
    {|if jexec "$JAIL" test -f "/etc/${APP}/env"; then|};
    {|  jexec "$JAIL" chown "root:${APP}" "/etc/${APP}/env"|};
    {|  jexec "$JAIL" chmod 0640 "/etc/${APP}/env"|};
    "else";
    {|  log "No /etc/${APP}/env yet: write it from the app's env.template, root:${APP} 0640, before the first activation"|};
    "fi";
  ]

(* erlang-runtimeNN installs its binaries under /usr/local/lib/erlangNN/bin
   only; the links put them on PATH. *)
let erlang_runtime_version packages =
  let prefix = "erlang-runtime" in
  List.find_map
    (fun package ->
      match String.starts_with ~prefix package with
      | false -> None
      | true ->
          let version =
            String.sub package (String.length prefix) (String.length package - String.length prefix)
          in
          if version <> "" && String.for_all (fun c -> c >= '0' && c <= '9') version then
            Some version
          else None)
    packages

let render_freebsd_native_elixir ~jail (app : App_config.t) (s : Strategy_config.freebsd_native_elixir) =
  let name = app.endpoint.name in
  String.concat "\n"
    ([
       render_jail_base ~layout:Release_pointer ~jail ~app:name ~jail_ip:app.endpoint.ip ();
       {|jexec "$JAIL" pkg bootstrap -y|};
       Printf.sprintf {|jexec "$JAIL" pkg install -y %s|}
         (String.concat " " s.packages);
     ]
    @ (match erlang_runtime_version s.packages with
      | Some version ->
          [
            Printf.sprintf
              {|jexec "$JAIL" sh -c 'for b in /usr/local/lib/erlang%s/bin/*; do ln -sf "$b" /usr/local/bin/; done'|}
              version;
          ]
      | None -> [])
    @ [ render_service_user ~layout:Release_pointer ~jail ~app:name () ]
    @ render_extra_steps app.extra_steps
    @ render_native_service (Rc_script.phoenix ~app:name ~env_names:app.env_names s))

let render_freebsd_package ~jail (app : App_config.t) (s : Strategy_config.freebsd_package) =
  String.concat "\n"
    ([
       render_jail_base ~jail ~app:app.endpoint.name ~jail_ip:app.endpoint.ip ();
       {|jexec "$JAIL" pkg bootstrap -y|};
       Printf.sprintf {|jexec "$JAIL" pkg install -y %s|} (String.concat " " s.packages);
       render_service_user ~jail ~app:app.endpoint.name ();
     ]
    @ render_extra_steps app.extra_steps)

(* A pinned upstream binary: fetch-verify-install and env-file templating.
   The checksum check and the write-once env file, which keeps every
   generated secret across reruns, are the safety-critical pieces this must
   not simplify away. Anything app-specific beyond that, such as a backup
   job, is an extra_steps script. The binary and rc.d script are installed
   into /usr/local, which is created here rather than left to whatever the
   package set happens to create. *)
let render_fetch_binary ~jail (app : App_config.t) (s : Strategy_config.fetch_binary) =
  let name = app.endpoint.name in
  let secrets = s.generated_secrets in
  String.concat "\n"
    ([
      render_jail_base ~jail ~app:name ~jail_ip:app.endpoint.ip
        ~extra_dirs:
          [ s.data_dir; "/usr/local/bin"; "/usr/local/sbin"; "/usr/local/etc/rc.d" ]
        ();
      Printf.sprintf "VERSION=%s" s.version;
      Printf.sprintf "BINARY_SHA256=%s" s.binary_sha256;
      {|jexec "$JAIL" pkg bootstrap -y|};
      Printf.sprintf {|jexec "$JAIL" pkg install -y %s|} (String.concat " " s.packages);
    ]
    @ [ render_service_user ~home:s.data_dir ~jail ~app:name () ]
    @ render_extra_steps app.extra_steps
    @ [
      "";
      "# Fetch and verify the binary. A tampered binary here compromises";
      "# every service that trusts it -- verification failure aborts and";
      "# leaves any existing binary untouched.";
      Printf.sprintf {|BIN_URL="%s"|} s.binary_url_template;
      Printf.sprintf {|TMP_BIN="/tmp/%s_${VERSION}"|} s.binary_name;
      {|fetch -o "$TMP_BIN" "$BIN_URL"|};
      {|ACTUAL="$(sha256 -q "$TMP_BIN")"|};
      {|if [ "$ACTUAL" != "$BINARY_SHA256" ]; then|};
      {|  rm -f "$TMP_BIN"|};
      {|  log "ERROR: checksum mismatch -- refusing to install"|};
      {|  log "  expected: ${BINARY_SHA256}"|};
      {|  log "  actual:   ${ACTUAL}"|};
      "  exit 1";
      "fi";
      Printf.sprintf
        {|install -m 0755 "$TMP_BIN" "${JROOT}/usr/local/bin/%s"|}
        s.binary_name;
      {|rm -f "$TMP_BIN"|};
      "";
      "# Render the env file. Written once -- re-running the script keeps";
      "# it, so a generated secret is never regenerated: a new one would";
      "# orphan whatever was already encrypted or signed with the old.";
      {|ENVFILE="${JROOT}/etc/${APP}/env"|};
      {|if [ -f "$ENVFILE" ]; then|};
      {|  log "Env file exists -- keeping it"|};
      "else";
      {|  TMP_ENV="${ENVFILE}.new"|};
    ]
    @ (if secrets = [] then [ {|  trap 'rm -f "$TMP_ENV"' EXIT HUP INT TERM|}; "  ( umask 0077" ]
       else
         [
           {|  SECRETS_DIR=$(mktemp -d "${TMPDIR:-/tmp}/${APP}-secrets.XXXXXX")|};
           {|  trap 'rm -rf "$SECRETS_DIR" "$TMP_ENV"' EXIT HUP INT TERM|};
           "  ( umask 0077";
         ]
         @ List.map
             (fun name -> Printf.sprintf {|    openssl rand -base64 32 >"${SECRETS_DIR}/%s"|} name)
             secrets)
    @ [ Printf.sprintf {|    awk -v jail_ip="$JAIL_IP" -v port="%s" \|} s.port ]
    @ List.map (fun (name, value) -> Printf.sprintf {|      -v v_%s="%s" \|} name value) s.env_values
    @ (if secrets = [] then [] else [ {|      -v secrets_dir="$SECRETS_DIR" \|} ])
    @ [ "      '" ]
    @ (if secrets = [] then []
       else
         [ "        BEGIN {" ]
         @ List.concat_map
             (fun name ->
               [
                 Printf.sprintf {|          getline s_%s < (secrets_dir "/%s")|} name name;
                 Printf.sprintf {|          close(secrets_dir "/%s")|} name;
               ])
             secrets
         @ [ "        }" ])
    @ [ "        {"; "          gsub(/__JAIL_IP__/, jail_ip)"; "          gsub(/__PORT__/, port)" ]
    @ List.map (fun (name, _) -> Printf.sprintf "          gsub(/__%s__/, v_%s)" name name) s.env_values
    @ List.map (fun name -> Printf.sprintf "          gsub(/__%s__/, s_%s)" name name) secrets
    @ [
      "          print";
      "        }";
      Printf.sprintf {|      ' "${SCRIPT_DIR}/%s" >"$TMP_ENV" )|} s.env_template_path;
      {|  if grep -q '__[A-Z_]\+__' "$TMP_ENV"; then|};
      {|    log "ERROR: unsubstituted placeholders in env:"|};
      {|    grep '__[A-Z_]\+__' "$TMP_ENV" >&2|};
      {|    rm -f "$TMP_ENV"|};
      "    exit 1";
      "  fi";
      {|  mv "$TMP_ENV" "$ENVFILE"|};
    ]
    @ (if secrets = [] then [] else [ {|  rm -rf "$SECRETS_DIR"|} ])
    @ [
      "  trap - EXIT HUP INT TERM";
      "fi";
      {|jexec "$JAIL" chown "root:${APP}" "/etc/${APP}/env"|};
      {|chmod 0640 "$ENVFILE"|};
      Printf.sprintf {|cp "${SCRIPT_DIR}/%s" "${JROOT}/usr/local/etc/rc.d/${APP}"|}
        s.rc_template_path;
      {|chmod +x "${JROOT}/usr/local/etc/rc.d/${APP}"|};
      Printf.sprintf {|jexec "$JAIL" chmod 0700 "%s"|} s.data_dir;
      Printf.sprintf {|jexec "$JAIL" sysrc %s_enable="YES"|} name;
      Printf.sprintf {|jexec "$JAIL" service %s restart 2>/dev/null |||} name;
      Printf.sprintf {|  jexec "$JAIL" service %s start|} name;
    ])

(* The ZFS dataset is a host resource, so a jail rendered under another name
   gets its own: the jail name's suffix beyond the app name is appended
   (zroot/notes under notestest is zroot/notestest). A jail name that does not
   extend the app name has no such suffix, and is refused rather than
   pointed at the real dataset. *)
let zfs_dataset_for ~jail ~app dataset =
  if jail = app then dataset
  else if String.length jail > String.length app && String.starts_with ~prefix:app jail then
    dataset ^ String.sub jail (String.length app) (String.length jail - String.length app)
  else
    invalid_arg
      (Printf.sprintf
         "Strategy: jail name %s does not extend app name %s, so its zfs_dataset cannot be \
          namespaced"
         jail app)

(* Port of a hand-written jail script's ZFS dataset creation with fail-closed
   mount-state verification. This is the safety-critical piece: a dataset
   that exists but is unmounted (e.g. after a host reboot) must never be
   silently treated as ready, or the jail would start against a directory
   that looks present but holds no persistent data. The verification runs
   between render_jail_setup and render_jail_start, as in the reference
   script, so the jail is neither registered nor started before its data
   dir is confirmed. *)
let render_freebsd_native_ocaml ~jail (app : App_config.t) (s : Strategy_config.freebsd_native_ocaml) =
  let name = app.endpoint.name in
  String.concat "\n"
    ([
      render_jail_setup ~layout:Release_pointer ~jail ~app:name ~jail_ip:app.endpoint.ip ();
      Printf.sprintf "ZFS_DATASET=%s"
        (zfs_dataset_for ~jail ~app:app.endpoint.name s.zfs_dataset);
      Printf.sprintf {|HOST_DATA_DIR="${JROOT}%s"|} s.data_dir;
      {|if ! zfs list -H -o name "$ZFS_DATASET" >/dev/null 2>&1; then|};
      {|  zfs create -o mountpoint="$HOST_DATA_DIR" "$ZFS_DATASET"|};
      {|elif [ "$(zfs get -H -o value mountpoint "$ZFS_DATASET")" != "$HOST_DATA_DIR" ]; then|};
      Printf.sprintf
        {|  echo "%s: ${ZFS_DATASET} mountpoint is not ${HOST_DATA_DIR}; refusing to move existing data" >&2|}
        jail;
      "  exit 1";
      "fi";
      {|if [ "$(zfs get -H -o value mounted "$ZFS_DATASET")" != "yes" ]; then|};
      Printf.sprintf {|  echo "%s: mounting persistent dataset ${ZFS_DATASET}"|}
        jail;
      Printf.sprintf
        {|  zfs mount "$ZFS_DATASET" || { echo "%s: failed to mount ${ZFS_DATASET}" >&2; exit 1; }|}
        jail;
      "fi";
      {|if [ "$(zfs get -H -o value mounted "$ZFS_DATASET")" != "yes" ] || [ ! -d "$HOST_DATA_DIR" ]; then|};
      Printf.sprintf
        {|  echo "%s: ${ZFS_DATASET} is not mounted at ${HOST_DATA_DIR}; refusing to start jail" >&2|}
        jail;
      "  exit 1";
      "fi";
      render_jail_start;
      {|jexec "$JAIL" pkg bootstrap -y|};
      Printf.sprintf {|jexec "$JAIL" pkg install -y %s|}
        (String.concat " " s.packages);
    ]
    @ [
      render_service_user ~layout:Release_pointer ~jail ~app:name ();
      Printf.sprintf {|jexec "$JAIL" chmod 0700 "%s"|} s.data_dir;
    ]
    @ render_extra_steps app.extra_steps
    @ render_native_service (Rc_script.ocaml ~app:name ~env_names:app.env_names s))

(* The package owns its service account and rc.d script. The host ZFS mount
   is checked before the jail is stopped or started; otherwise an unmounted
   dataset could silently turn retained data into files on the root
   filesystem. *)
let render_freebsd_package_service ~jail (app : App_config.t)
    (s : Strategy_config.freebsd_package_service) =
  let data_dir = s.data_dir in
  String.concat "\n"
    ([
      render_jail_setup ~stop_before_setup:false ~jail ~app:app.endpoint.name
        ~jail_ip:app.endpoint.ip ();
      "ZFS_DATASET=" ^ Shell.quote (zfs_dataset_for ~jail ~app:app.endpoint.name s.zfs_dataset);
      "HOST_DATA_DIR=\"${JROOT}" ^ data_dir ^ "\"";
      {|if ! zfs list -H -o name "$ZFS_DATASET" >/dev/null 2>&1; then|};
      {|  zfs create -o mountpoint="$HOST_DATA_DIR" "$ZFS_DATASET"|};
      {|elif [ "$(zfs get -H -o value mountpoint "$ZFS_DATASET")" != "$HOST_DATA_DIR" ]; then|};
      {|  echo "dataset mountpoint mismatch; refusing to start jail" >&2|};
      "  exit 1";
      "fi";
      {|if [ "$(zfs get -H -o value mounted "$ZFS_DATASET")" != "yes" ]; then|};
      {|  zfs mount "$ZFS_DATASET"|};
      "fi";
      {|if [ "$(zfs get -H -o value mounted "$ZFS_DATASET")" != "yes" ] || [ ! -d "$HOST_DATA_DIR" ]; then|};
      {|  echo "dataset is not mounted; refusing to start jail" >&2|};
      "  exit 1";
      "fi";
      {|service jail stop "$JAIL" 2>/dev/null || true|};
      render_jail_start;
      {|jexec "$JAIL" pkg bootstrap -y|};
      "jexec \"$JAIL\" pkg install -y " ^ String.concat " " s.packages;
      "jexec \"$JAIL\" chown " ^ s.data_owner ^ ":" ^ s.data_owner ^ " " ^ Shell.quote data_dir;
      {|jexec "$JAIL" sysrc |} ^ s.service ^ {|_enable=YES|};
      {|jexec "$JAIL" sysrc |} ^ s.service ^ "_args=" ^ Shell.quote (String.concat " " s.service_args);
      Printf.sprintf {|jexec "$JAIL" service %s onestatus >/dev/null 2>&1 |||} s.service;
      Printf.sprintf {|  jexec "$JAIL" service %s start|} s.service;
    ] @ render_extra_steps app.extra_steps)

(* [jail_name] is the host-side jail name, the endpoint name by default; the
   app keeps its own name inside the jail whatever it is. *)
let render_jail_script ?jail_name (app : App_config.t) =
  let jail = Option.value jail_name ~default:app.endpoint.name in
  match app.strategy with
  | Strategy_config.Freebsd_native_elixir s -> render_freebsd_native_elixir ~jail app s
  | Strategy_config.Freebsd_package s -> render_freebsd_package ~jail app s
  | Strategy_config.Fetch_binary s -> render_fetch_binary ~jail app s
  | Strategy_config.Freebsd_native_ocaml s -> render_freebsd_native_ocaml ~jail app s
  | Strategy_config.Freebsd_package_service s -> render_freebsd_package_service ~jail app s
