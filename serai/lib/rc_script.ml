type t = { service : string; script : string }

(* Every {key} in [template] replaced by its value. The values are declared
   names and words, already restricted by Strategy_config and
   Network_endpoint, so none of them can carry shell syntax. *)
let fill template bindings =
  List.fold_left
    (fun text (key, value) ->
      let key = "{" ^ key ^ "}" in
      let buffer = Buffer.create (String.length text) in
      let rec go i =
        match String.index_from_opt text i '{' with
        | Some j when j + String.length key <= String.length text
                      && String.sub text j (String.length key) = key ->
            Buffer.add_string buffer (String.sub text i (j - i));
            Buffer.add_string buffer value;
            go (j + String.length key)
        | Some j ->
            Buffer.add_string buffer (String.sub text i (j - i + 1));
            go (j + 1)
        | None -> Buffer.add_string buffer (String.sub text i (String.length text - i))
      in
      go 0;
      Buffer.contents buffer)
    template bindings

let header ~require = {|#!/bin/sh
#
# PROVIDE: {svc}
# REQUIRE: |} ^ require ^ {|
# KEYWORD: shutdown
#
# Generated by serai for {app}; do not hand-edit.
# shellcheck disable=SC2034 # rc.subr reads these variables

. /etc/rc.subr

name="{svc}"
rcvar="{svc}_enable"
load_rc_config "$name"
: "${{svc}_enable:=NO}"

app_user="{app}"
envfile="/etc/{app}/env"
logfile="/var/log/{app}/{svc}.log"
start_cmd="{svc}_start"
stop_cmd="{svc}_stop"
status_cmd="{svc}_status"
|}

let migrate_commands = {|extra_commands="migrate"
migrate_cmd="{svc}_migrate"
|}

(* Loads the operator's env into this shell for su -m to pass on, refusing
   it unless every name the env.template declares is set and filled in. The
   names are Env_template names, so eval sees only [A-Z0-9_]. *)
let load_env env_names = {|
# The operator's env.
{svc}_env() {
    [ -r "$envfile" ] || { echo "$name: cannot read $envfile" >&2; return 1; }
    set -a
    # shellcheck disable=SC1090 # the operator's runtime configuration
    . "$envfile"
    HOME=/var/db/{app}
    set +a
|} ^ (match env_names with
     | [] -> ""
     | names -> {|    # Every variable the app's env.template declares.
    for var in |} ^ String.concat " " names ^ {|; do
        eval "value=\${$var:-}"
        # shellcheck disable=SC2154 # assigned by the eval above
        case "$value" in
            ''|REPLACE_ME) echo "$name: $var is not set in $envfile" >&2; return 1 ;;
        esac
    done
|}) ^ {|}

{svc}_dirs() {
    mkdir -p /var/run/{app} /var/log/{app}
    chown "$app_user" /var/run/{app} /var/log/{app}
}
|}

let phoenix env_names = {|release_bin="/opt/{app}/bin/{release}"
|} ^ load_env env_names ^ {|
# A release needs its distribution cookie for stop and pid as well as start.
{svc}_release_env() {
    {svc}_env || return 1
    : "${RELEASE_COOKIE:?$name: RELEASE_COOKIE not set in $envfile}"
    set -a
    RELEASE_TMP=${RELEASE_TMP:-/var/run/{app}}
    set +a
}

{svc}_start() {
    {svc}_dirs
    {svc}_release_env || return 1
    su -m "$app_user" -c "$release_bin daemon" </dev/null >>"$logfile" 2>&1
}

{svc}_stop() {
    {svc}_release_env || return 1
    su -m "$app_user" -c "$release_bin stop" >>"$logfile" 2>&1 \
        || echo "$name not running"
}

{svc}_status() {
    {svc}_release_env || return 1
    pid=$(su -m "$app_user" -c "$release_bin pid" 2>/dev/null)
    if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
        echo "$name running as PID $pid"
    else
        echo "$name not running"
        return 1
    fi
}
|}

let phoenix_migrate = {|
{svc}_migrate() {
    {svc}_release_env || return 1
    su -m "$app_user" -c "$release_bin eval '{eval}()'" </dev/null
}
|}

let ocaml env_names = {|procname="/opt/{app}/bin/{app}"
pidfile="/var/run/{app}/{app}.pid"
supervisor_pidfile="/var/run/{app}/supervisor.pid"
|} ^ load_env env_names ^ {|
{svc}_start() {
    {svc}_dirs
    {svc}_env || return 1
    echo "Starting $name."
    # daemon -u resets the environment, so the env is sourced again after
    # privileges are dropped; the check above only refuses a bad file.
    /usr/sbin/daemon -c -f -P "$supervisor_pidfile" -p "$pidfile" -o "$logfile" \
        -u "$app_user" -- /bin/sh -c \
        "set -a; . $envfile; HOME=/var/db/{app}; set +a; exec $procname {serve_args}"
}

{svc}_stop() {
    stopped=0
    for file in "$supervisor_pidfile" "$pidfile"; do
        [ -f "$file" ] || continue
        pid="$(cat "$file" 2>/dev/null)" || continue
        if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
            [ "$stopped" -eq 1 ] || echo "Stopping $name."
            kill "$pid" 2>/dev/null
            wait_for_pids "$pid"
            stopped=1
        fi
        rm -f "$file"
    done
    [ "$stopped" -eq 1 ] || { echo "$name not running."; return 1; }
}

{svc}_status() {
    if [ -f "$pidfile" ] && kill -0 "$(cat "$pidfile")" 2>/dev/null; then
        echo "$name is running as pid $(cat "$pidfile")."
    else
        echo "$name is not running."
        return 1
    fi
}
|}

let ocaml_migrate = {|
{svc}_migrate() {
    {svc}_env || return 1
    su -m "$app_user" -c "$procname {migrate}" </dev/null
}
|}

let footer = {|
run_rc_command "$1"
|}

let phoenix_template = phoenix
let ocaml_template = ocaml

let phoenix ~app ~env_names (s : Strategy_config.freebsd_native_elixir) =
  let migrate = Option.is_some s.migrate in
  let script =
    header ~require:"NETWORKING"
    ^ (if migrate then migrate_commands else "")
    ^ phoenix_template env_names
    ^ (if migrate then phoenix_migrate else "")
    ^ footer in
  { service = s.release_name;
    script = fill script
      [ ("svc", s.release_name); ("app", app); ("release", s.release_name);
        ("eval", Option.value s.migrate ~default:"") ] }

let ocaml ~app ~env_names (s : Strategy_config.freebsd_native_ocaml) =
  let migrate = Option.is_some s.migrate in
  let script =
    header ~require:"NETWORKING FILESYSTEMS"
    ^ (if migrate then migrate_commands else "")
    ^ ocaml_template env_names
    ^ (if migrate then ocaml_migrate else "")
    ^ footer in
  { service = app;
    script = fill script
      [ ("svc", app); ("app", app);
        ("serve_args", String.concat " " s.serve_args);
        ("migrate", String.concat " " (Option.value s.migrate ~default:[])) ] }

let render (app : App_config.t) =
  match app.strategy with
  | Strategy_config.Freebsd_native_elixir s ->
      Some (phoenix ~app:app.endpoint.name ~env_names:app.env_names s)
  | Strategy_config.Freebsd_native_ocaml s ->
      Some (ocaml ~app:app.endpoint.name ~env_names:app.env_names s)
  | Strategy_config.(Freebsd_package _ | Fetch_binary _ | Freebsd_package_service _) -> None
